"""Plate-only uneaten models from the already pinned failure/slime asset families.

No new textures or pose calibration. Held and placed plates share one ordered
catalog; the source item identity and saved override precedence remain exact.
"""
from copy import deepcopy
from functools import lru_cache
import json
from pathlib import Path
from build_failure_skewer_held import NAMES, selectors, source as failure_source

ROOT = Path(__file__).resolve().parents[1]
RP = ROOT / 'projects/grilling/gameplay_core/resource_pack'
BP = ROOT / 'projects/grilling/gameplay_core/behavior_pack'
HELD_START, WORLD_START = 40, 115


@lru_cache(maxsize=1)
def catalog():
    failure_source()
    result, failure = [], {}
    for frame in range(5):
        geo = json.loads((RP / f'models/entity/slime_frames/stage0_frame{frame}.geo.json').read_text())['minecraft:geometry'][0]
        result.append({'name': f'slime_{frame}', 'geometry': geo, 'texture': 'textures/slime_frames/slime_frame_0'})
    geometries = {g['description']['identifier']: g for g in json.loads((RP / 'models/entity/failure_skewer_held.geo.json').read_text())['minecraft:geometry']}
    for name in NAMES:
        state, source = selectors(name)
        chosen = sorted(set(state[::4] + source[::4]))
        desc = json.loads((RP / f'attachables/{name}.attachable.json').read_text())['minecraft:attachable']['description']
        lookup = {}
        for index in chosen:
            lookup[index] = len(result)
            alias = 'model_' + str(index)
            result.append({'name': f'{name}_{index}', 'geometry': geometries[desc['geometry'][alias]], 'texture': desc['textures'][alias]})
        failure['kaleidoscope_grilling:' + name] = {'states': [lookup[i] for i in state[::4]], 'sources': [lookup[i] for i in source[::4]]}
    return result, failure


def lifted_cubes(row, offset=0):
    # Existing held source meshes have one +24 model-space lift; no parent
    # transforms are baked into the uneaten model bones.
    cubes = []
    for bone in row['geometry']['bones']:
        assert not any(bone.get(k) for k in ('rotation', 'position', 'scale')), 'unreviewed source transform'
        for source in bone.get('cubes', []):
            cube = deepcopy(source)
            cube['origin'][1] += offset
            if 'pivot' in cube:
                cube['pivot'][1] += offset
            cubes.append(cube)
    return cubes


def data_bytes():
    rows, failure = catalog()
    return ('// Generated by tools/plate_special_models.py; exact uneaten source-model selection.\n'
            'export const PLATE_SPECIAL_HELD_START=40;\n'
            'export const PLATE_SPECIAL_WORLD_START=115;\n'
            f'export const PLATE_SPECIAL_COUNT={len(rows)};\n'
            'export const PLATE_FAILURE_MODELS=Object.freeze(' + json.dumps(failure, separators=(',', ':')) + ');\n').encode()


def geometry_key(geometry):
    """Share only identical dimensions and complete cube/rotation/UV payloads."""
    desc = geometry['description']
    return json.dumps([desc['texture_width'], desc['texture_height'],
                       [cube for bone in geometry['bones'] for cube in bone.get('cubes', [])]],
                      sort_keys=True, separators=(',', ':'))
